from dto.document_data import DocumentData
from dto.llm_schemas import Chunk
from dto.result import Result
from logs.logger_singleton import Logger
from langchain_core.documents import Document

logger = Logger("utils-file-llm-mapper")


def chunk_to_result(chunk: Chunk, document: Document) -> Result:
    """
    Convert a structured LLM Chunk into a Result object by combining
    the chunk content with metadata from the source document.

    Args:
        chunk (Chunk): A structured chunk generated by the LLM containing
            headline, summary, and original text.
        document (Document): The source LangChain document associated with the chunk.

    Returns:
        Result: A Result object containing formatted page content and metadata.
    """
    doc_data = DocumentData(
        page_content=document.page_content, metadata=document.metadata
    )
    return Result(
        page_content=f"{chunk.headline}\n\n{chunk.summary}\n\n{chunk.original_text}",
        metadata={
            "source": doc_data.source,
            "type": doc_data.doc_type,
        },
    )
